function status_badge(string $status): string
{
    $colors = [
        'new' => 'badge-blue', 'contacted' => 'badge-purple', 'in_progress' => 'badge-orange',
        'completed' => 'badge-green', 'closed' => 'badge-gray', 'delivered' => 'badge-green',
        'planning' => 'badge-blue', 'review' => 'badge-purple', 'active' => 'badge-green',
        'inactive' => 'badge-gray', 'unpaid' => 'badge-orange', 'paid' => 'badge-green',
        'overdue' => 'badge-red', 'cancelled' => 'badge-gray', 'pending' => 'badge-orange',
        'failed' => 'badge-red', 'open' => 'badge-blue', 'answered' => 'badge-green', 'closed' => 'badge-gray',
    ];
    $color = $colors[$status] ?? 'badge-gray';
    return '<span class="badge ' . e($color) . '">' . e(ucwords(str_replace('_', ' ', $status))) . '</span>';
}

function render_stars(int $rating): string
{
    $out = '';
    for ($i = 1; $i <= 5; $i++) {
        $out .= '<span class="star' . ($i <= $rating ? ' filled' : '') . '">' . icon('star') . '</span>';
    }
    return $out;
}

