    return $customer;
}

function require_admin(): array
{
    $admin = current_admin();
    if ($admin === null) {
        redirect('admin/login.php');
    }
    return $admin;
}

function time_ago(string $datetime): string
{
    $ts = strtotime($datetime);
    if (!$ts) {
        return $datetime;
    }
    $diff = time() - $ts;
    if ($diff < 60) return 'just now';
    if ($diff < 3600) return floor($diff / 60) . ' min ago';
    if ($diff < 86400) return floor($diff / 3600) . ' hours ago';
    if ($diff < 2592000) return floor($diff / 86400) . ' days ago';
    return date('d M Y', $ts);
}

function money(float|int|string $amount): string
{
    return 'BDT ' . number_format((float)$amount, 0);
}

function upload_file(array $file, string $subdir, array $allowedExt = ['jpg', 'jpeg', 'png', 'gif', 'webp', 'svg', 'pdf', 'zip', 'docx', 'txt']): ?string
{
    if (!isset($file['error']) || $file['error'] !== UPLOAD_ERR_OK) {
        return null;
    }
    if ($file['size'] > MAX_UPLOAD_MB * 1024 * 1024) {
        return null;
    }
    $ext = strtolower(pathinfo($file['name'], PATHINFO_EXTENSION));
    if (!in_array($ext, $allowedExt, true)) {
        return null;
    }
    $dir = UPLOAD_DIR . '/' . $subdir;
    if (!is_dir($dir)) {
        mkdir($dir, 0777, true);
    }
    $filename = uniqid() . '_' . slugify(pathinfo($file['name'], PATHINFO_FILENAME)) . '.' . $ext;
    $dest = $dir . '/' . $filename;
    if (!move_uploaded_file($file['tmp_name'], $dest)) {
        return null;
    }
    return 'uploads/' . $subdir . '/' . $filename;
}

function notify(int $userId, string $type, string $title, string $message, ?string $link = null): void
{
    $stmt = db()->prepare('INSERT INTO notifications (user_type, user_id, title, message, link) VALUES (?, ?, ?, ?, ?)');
    $stmt->execute([$type, $userId, $title, $message, $link]);
}

function unread_count(string $type, int $userId): int
{
    $stmt = db()->prepare('SELECT COUNT(*) FROM notifications WHERE user_type = ? AND user_id = ? AND is_read = 0');
    $stmt->execute([$type, $userId]);
    return (int)$stmt->fetchColumn();
}

